# Rasterise a monospace system font into 1-bit glyph bitmaps for the LCD.
# Regenerate src/fonts.h with:
#   pwsh tools/gen_font.ps1 -Out src/fonts.h
param([string]$Out)
Add-Type -AssemblyName System.Drawing

function Gen-Font([string]$name, [string]$family, [int]$px, [System.Drawing.FontStyle]$style) {
    $font = New-Object System.Drawing.Font($family, $px, $style, [System.Drawing.GraphicsUnit]::Pixel)
    # Measure the advance of a wide glyph with typographic (no padding) format.
    $probe = New-Object System.Drawing.Bitmap(200, 200)
    $g = [System.Drawing.Graphics]::FromImage($probe)
    $fmt = [System.Drawing.StringFormat]::GenericTypographic
    $fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
    $sz = $g.MeasureString("MMMMMMMMMM", $font, 1000, $fmt)
    $cellW = [int][Math]::Ceiling($sz.Width / 10)
    $cellH = [int][Math]::Ceiling($font.GetHeight($g))
    $g.Dispose(); $probe.Dispose()

    $rowBytes = [int][Math]::Ceiling($cellW / 8)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("// $family ${px}px $style : cell ${cellW}x${cellH}, $rowBytes byte(s)/row, ASCII 32..126")
    [void]$sb.AppendLine("static const uint8_t ${name}_DATA[95][$($cellH * $rowBytes)] = {")
    for ($c = 32; $c -le 126; $c++) {
        $bmp = New-Object System.Drawing.Bitmap($cellW, $cellH)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.Clear([System.Drawing.Color]::Black)
        $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
        $g.DrawString([string][char]$c, $font, [System.Drawing.Brushes]::White, 0, 0, $fmt)
        $g.Dispose()
        $bytes = @()
        for ($y = 0; $y -lt $cellH; $y++) {
            for ($b = 0; $b -lt $rowBytes; $b++) {
                $v = 0
                for ($bit = 0; $bit -lt 8; $bit++) {
                    $x = $b * 8 + $bit
                    if ($x -lt $cellW -and $bmp.GetPixel($x, $y).R -gt 127) { $v = $v -bor (0x80 -shr $bit) }
                }
                $bytes += ('0x{0:x2}' -f $v)
            }
        }
        $bmp.Dispose()
        $label = if ($c -eq 92) { "backslash" } else { [string][char]$c }
        [void]$sb.AppendLine("  /* '$label' */ {" + ($bytes -join ",") + "},")
    }
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("static const Font $name = { $cellW, $cellH, $rowBytes, &${name}_DATA[0][0] };")
    [void]$sb.AppendLine("")
    return $sb.ToString()
}

$hdr = New-Object System.Text.StringBuilder
[void]$hdr.AppendLine("#pragma once")
[void]$hdr.AppendLine("// Generated by gen_font.ps1 (GDI+ rasterisation of a system font). Do not edit.")
[void]$hdr.AppendLine("#include <stdint.h>")
[void]$hdr.AppendLine("")
[void]$hdr.AppendLine("struct Font {")
[void]$hdr.AppendLine("  uint8_t width;      // cell width in px (fixed advance)")
[void]$hdr.AppendLine("  uint8_t height;     // cell height in px")
[void]$hdr.AppendLine("  uint8_t rowBytes;   // bytes per bitmap row")
[void]$hdr.AppendLine("  const uint8_t* data;// 95 glyphs (ASCII 32..126), MSB-first rows")
[void]$hdr.AppendLine("};")
[void]$hdr.AppendLine("")
[void]$hdr.Append((Gen-Font "FONT_SMALL" "Consolas" 16 ([System.Drawing.FontStyle]::Regular)))
[void]$hdr.Append((Gen-Font "FONT_MED"   "Consolas" 20 ([System.Drawing.FontStyle]::Bold)))
[void]$hdr.Append((Gen-Font "FONT_LARGE" "Consolas" 24 ([System.Drawing.FontStyle]::Bold)))
[void]$hdr.Append((Gen-Font "FONT_XL"    "Consolas" 36 ([System.Drawing.FontStyle]::Bold)))
[System.IO.File]::WriteAllText($Out, $hdr.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out"
